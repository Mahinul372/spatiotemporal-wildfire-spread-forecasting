# --- helpers ----------------------------------------------------------------

def load_members(manifest_path: str | Path | None) -> list[tuple[str, int]]:
    """Embedded list, or a local manifest.json (same schema) if given."""
    if manifest_path is None:
        return list(MEMBERS)
    payload = json.loads(Path(manifest_path).read_text())
    members = sorted((f["name"], int(f["bytes"])) for f in payload["files"])
    if len(members) != 394:
        raise ValueError(
            f"{manifest_path}: expected 394 members, got {len(members)}")
    return members


def plan(dest: Path, members: list[tuple[str, int]]) -> dict:
    """Split members into present (size matches) / missing / wrong-size."""
    present, missing, wrong_size = [], [], []
    for name, size in members:
        p = dest / name
        if p.exists():
            if p.stat().st_size == size:
                present.append(name)
            else:
                wrong_size.append((name, p.stat().st_size, size))
        else:
            missing.append(name)
    return {"present": present, "missing": missing, "wrong_size": wrong_size,
            "total_bytes": sum(s for _, s in members)}


def verify_only(dest: Path, members: list[tuple[str, int]]) -> int:
    p = plan(dest, members)
    print(f"destination: {dest}")
    print(f"present (size OK): {len(p['present'])}/394")
    print(f"missing:           {len(p['missing'])}")
    print(f"wrong size:        {len(p['wrong_size'])}")
    for name, have, want in p["wrong_size"][:10]:
        print(f"  WRONG SIZE {name}: have {have}, want {want}")
    for name in p["missing"][:10]:
        print(f"  MISSING {name}")
    ok = not p["missing"] and not p["wrong_size"]
    print("VERIFY " + ("OK — all 394 files present with matching sizes"
                       if ok else "FAILED"))
    return 0 if ok else 1


def download(dest: Path, members: list[tuple[str, int]],
             limit: int | None = None) -> int:
    try:
        import remotezip
    except ImportError:
        print("ERROR: remotezip is not installed. Run: pip install remotezip",
              file=sys.stderr)
        return 2
    wanted = dict(members)
    if limit is not None:
        wanted = dict(list(members)[:limit])
    p = plan(dest, list(wanted.items()))
    to_fetch = [n for n in p["missing"]] + [n for n, _, _ in p["wrong_size"]]
    if p["wrong_size"]:
        print(f"re-downloading {len(p['wrong_size'])} wrong-size files")
    print(f"{len(p['present'])} already present, "
          f"{len(to_fetch)} to download "
          f"({sum(wanted[n] for n in to_fetch) / 1e9:.2f} GB)")
    if not to_fetch:
        print("Nothing to download.")
        return 0
    dest.mkdir(parents=True, exist_ok=True)
    n_ok, n_fail = 0, 0
    with remotezip.RemoteZip(ZIP_URL) as z:
        archive_names = set(z.namelist())
        for i, name in enumerate(to_fetch, 1):
            if name not in archive_names:
                print(f"[{i}/{len(to_fetch)}] MISSING IN ARCHIVE: {name}")
                n_fail += 1
                continue
            out = dest / name
            out.parent.mkdir(parents=True, exist_ok=True)
            try:
                data = z.read(name)
            except Exception as e:  # noqa: BLE001 - network errors vary
                print(f"[{i}/{len(to_fetch)}] FAILED {name}: {e}")
                n_fail += 1
                continue
            if len(data) != wanted[name]:
                print(f"[{i}/{len(to_fetch)}] SIZE MISMATCH {name}: "
                      f"got {len(data)}, want {wanted[name]}")
                n_fail += 1
                continue
            out.write_bytes(data)
            n_ok += 1
            if i % 25 == 0 or i == len(to_fetch):
                print(f"[{i}/{len(to_fetch)}] ok ({n_ok} done, "
                      f"{n_fail} failed)")
    print(f"done: {n_ok} downloaded, {n_fail} failed")
    return 0 if n_fail == 0 else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dest", required=True,
                    help="target dir, e.g. /content/drive/MyDrive/wildfire/data/raw")
    ap.add_argument("--manifest", default=None,
                    help="optional local manifest.json to use instead of "
                         "the embedded member list")
    ap.add_argument("--verify-only", action="store_true",
                    help="check which files are present; download nothing")
    ap.add_argument("--dry-run", action="store_true",
                    help="parse args + list the plan; no network, no writes")
    ap.add_argument("--limit", type=int, default=None,
                    help="download only the first N members (testing)")
    args = ap.parse_args(argv)
    members = load_members(args.manifest)
    dest = Path(args.dest)
    if args.dry_run:
        p = plan(dest, members)
        print(f"dry run: {len(members)} members, "
              f"{p['total_bytes']} bytes total")
        print(f"present: {len(p['present'])}, missing: {len(p['missing'])}, "
              f"wrong-size: {len(p['wrong_size'])}")
        print(f"first member: {members[0]}")
        print(f"last member:  {members[-1]}")
        return 0
    if args.verify_only:
        return verify_only(dest, members)
    return download(dest, members, limit=args.limit)


if __name__ == "__main__":
    raise SystemExit(main())
